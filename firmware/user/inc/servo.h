/*********************************************************************************************************************
* 文件名称          servo
* 功能说明          摆杆舵机驱动（25kg·cm 金属齿，50Hz 标准舵机协议）
*                   信号脚：拓展板 PWM_B4（TIM_A1_CH0；若实物接 B3 改 PWM_TIM_A1_CH1_B3，反馈写死）
*                   三个标定值由 A07 串口扫角实测定：中位=摆杆水平，MIN/MAX=不顶死结构的安全边界
*                   注意：部分 25kg 舵机是 270° 版（500~2500µs 对应 270°），角度以实测为准
********************************************************************************************************************/

#ifndef _servo_h_
#define _servo_h_

#include "zf_common_headfile.h"

#define SERVO_MID_US    ( 1815 )                // 中位脉宽（摆杆水平）——实测摆杆水平时钢珠居中，2026-07-31 标定
#define SERVO_MIN_US    ( 1300 )                // 行程安全下限：2026-07-31 实测齿条机械下限约 1300us，严禁低于
#define SERVO_MAX_US    ( 2500 )                // 行程安全上限：2026-07-31 实测齿条机械上限约 2500us，严禁超过

#define SERVO_ABS_MIN_US    ( 500  )            // 舵机电气极限（set_us 钳位用）
#define SERVO_ABS_MAX_US    ( 2500 )

void   servo_init   (void);                     // 50Hz，上电输出中位脉宽（防猛冲）
void   servo_set_us (uint16 us);                // 500~2500，超界钳位
uint16 servo_get_us (void);

#endif
